def resolve_brand(part_manuf_raw: str, part_desc_raw: str, e1_brand: str = "") -> dict:
\
\
       
    clean_manuf = (part_manuf_raw or "").strip()
    clean_desc = (part_desc_raw or "").strip().lower()
    clean_e1 = (e1_brand or "").strip().lower()
    
    base_manuf = clean_manuf.split("(")[0].strip() if "(" in clean_manuf else clean_manuf
    
    for key, data in BRAND_MASTER.items():
        if key in base_manuf.lower() or key in clean_desc or (clean_e1 and key in clean_e1):
            return data
            
    if base_manuf and base_manuf not in ["-", "-- Unbranded --", ""]:
        return {
            "mfr_name": base_manuf,
            "brand_name": base_manuf,
            "mfr_code": base_manuf[:4].upper(),
            "brand_code": base_manuf[:4].upper(),
            "mfr_url_template": f"https://www.google.com/search?q={base_manuf}+{{mpn}}"
        }
        
    return {
        "mfr_name": "Generic Industrial",
        "brand_name": "Unbranded",
        "mfr_code": "GEN",
        "brand_code": "GEN",
        "mfr_url_template": ""
    }

def resolve_taxonomy(part_desc_raw: str) -> dict:
\
\
       
    desc = (part_desc_raw or "").lower()
    
    for key, tax in TAXONOMY_MAP.items():
        if key in desc:
            return tax
            
    if "sanding" in desc or "abranet" in desc or "hiolit" in desc or "stikit" in desc or "cubitron" in desc or "abrasive" in desc:
        if "disc" in desc or "5\"" in desc or "6\"" in desc:
            return TAXONOMY_MAP["sanding disc"]
        return TAXONOMY_MAP["sanding belt"]
    elif "blade" in desc or "saw" in desc:
        return TAXONOMY_MAP["saw blade"]
    elif "dish" in desc or "wash" in desc:
        return TAXONOMY_MAP["dishwasher"]
    elif "light" in desc or "led" in desc or "lamp" in desc or "watt" in desc or "lumen" in desc:
        return TAXONOMY_MAP["lamp"]
    elif "cplg" in desc or "coupling" in desc or "fitting" in desc or "valve" in desc:
        return TAXONOMY_MAP["coupling"]
    elif "wood" in desc or "board" in desc or "stud" in desc or "plywood" in desc or "lumber" in desc:
        return TAXONOMY_MAP["lumber"]
        
    return {
        "dept": "Industrial Supplies",
        "class_name": "General Industrial",
        "fine": "Hardware & Accessories",
        "classpath": "Industrial Supplies > Maintenance, Repair & Operations > Hardware & Fasteners",
        "unspsc": "31160000",
        "product_name": "Industrial Component"
    }
